#!/usr/bin/env node
/**
 * inject-credentials.js
 * Writes output/<slug>/config.js (gitignored) with the browser credentials from
 * .env and the per-demo names from output/<slug>/demo.config.json. demo.html is
 * never read or modified; it loads config.js via a <script> tag.
 * Run after `pnpm run setup -- --slug <name>` writes demo.config.json.
 *
 * Usage: node scripts/inject-credentials.js --slug <name>
 *        node scripts/inject-credentials.js --all
 */

const fs = require('fs');
const path = require('path');
const { ROOT, loadEnv, readDemoConfig, demoDir, foreignSlugRefs } = require('./lib/config');

const HEADER = '// Generated by scripts/inject-credentials.js — contains credentials. Gitignored; never commit.\n';

// Builds the config.js text. env supplies the secrets, names supplies index/agentId.
function buildConfigJs(env, names) {
  const obj = {
    url: env.ES_URL || '',
    apiKey: env.ES_API_KEY_READONLY || '',
    index: names.index || '',
    kibanaUrl: env.KIBANA_URL || '',
    kibanaApiKey: env.KIBANA_API_KEY || '',
    agentId: names.agentId || '',
  };
  return `${HEADER}window.ES_CONFIG = ${JSON.stringify(obj, null, 2)};\n`;
}

function writeConfigJs(slug, env, names) {
  const outPath = path.join(demoDir(slug), 'config.js');
  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, buildConfigJs(env, names), { mode: 0o600 });
  fs.chmodSync(outPath, 0o600); // mode above is ignored when the file already exists
  return outPath;
}

function fail(msg) {
  console.error(msg);
  process.exit(1);
}

// Writes config.js for one slug; exits nonzero on any problem.
function injectSlug(slug, env) {
  const cfg = readDemoConfig(slug);
  if (!cfg || !cfg.indexName || !cfg.agentId) {
    fail(`ERROR: output/${slug}/demo.config.json is missing or lacks indexName/agentId.\n  Run: pnpm run setup -- --slug ${slug}`);
  }

  const refs = foreignSlugRefs(slug, cfg);
  if (refs.length) {
    const lines = refs.map(r => `  ${r.field} = ${r.value} (contains slug "${r.otherSlug}")`);
    fail(`ERROR: output/${slug}/demo.config.json references another demo:\n${lines.join('\n')}`);
  }

  const outPath = writeConfigJs(slug, env, { index: cfg.indexName, agentId: cfg.agentId });

  console.log(`\n✓ Wrote ${path.relative(ROOT, outPath)}`);
  console.log(`  ES_URL:          ${env.ES_URL}`);
  console.log(`  index:           ${cfg.indexName}`);
  console.log(`  KIBANA_URL:      ${env.KIBANA_URL}`);
  console.log(`  agentId:         ${cfg.agentId}`);
  console.log(`  ES_API_KEY_READONLY: set`);
  console.log(`  KIBANA_API_KEY:  ${env.KIBANA_API_KEY ? 'set' : 'NOT SET — GenAI mode will fail'}`);
}

function main() {
  const args = process.argv.slice(2);
  const slugIdx = args.indexOf('--slug');
  const slug = slugIdx !== -1 && args[slugIdx + 1] ? args[slugIdx + 1] : null;
  const all = args.includes('--all');

  if (!slug && !all) {
    console.error('ERROR: --slug <name> or --all is required');
    console.error('  Usage: node scripts/inject-credentials.js --slug cpkc');
    console.error('         node scripts/inject-credentials.js --all');
    process.exit(1);
  }

  let env;
  try {
    env = loadEnv();
  } catch (err) {
    fail(`ERROR: ${err.message}`);
  }

  const required = ['ES_URL', 'ES_API_KEY_READONLY', 'KIBANA_URL'];
  const missing = required.filter(k => !env[k] || env[k].startsWith('your_'));
  if (missing.length) {
    fail(`ERROR: Missing or placeholder values in .env: ${missing.join(', ')}`);
  }
  if (!env.KIBANA_API_KEY) {
    console.warn('WARNING: KIBANA_API_KEY not set — Agent Builder (GenAI mode) will return 403.');
    console.warn('  See README for how to create this key, then re-run inject.');
  }

  let slugs;
  if (all) {
    const outDir = path.join(ROOT, 'output');
    const dirs = fs.existsSync(outDir)
      ? fs.readdirSync(outDir, { withFileTypes: true }).filter(e => e.isDirectory() && e.name !== 'test').map(e => e.name).sort()
      : [];
    slugs = [];
    for (const d of dirs) {
      if (fs.existsSync(path.join(outDir, d, 'demo.config.json'))) slugs.push(d);
      else console.log(`Note: skipping output/${d} (no demo.config.json)`);
    }
    if (!slugs.length) fail('ERROR: no output/<slug>/demo.config.json found. Run setup first.');
  } else {
    slugs = [slug];
  }

  for (const s of slugs) injectSlug(s, env);

  console.log(`\n  Run: pnpm dev`);
  console.log(`  Open: http://localhost:3000/${slugs[0]}/demo.html\n`);
}

module.exports = { buildConfigJs };

if (require.main === module) main();
