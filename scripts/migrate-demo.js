#!/usr/bin/env node
/**
 * migrate-demo.js
 *
 * TEMPORARY: delete after all demos are migrated.
 *
 * Migrates existing demo pages (credentials inlined in ES_CONFIG, or {{TOKENS}})
 * to the config.js model: writes demo.config.json (names only), rewrites the page
 * to load credentials from config.js, and loosens the CSP connect-src.
 * Never prints or copies key values; only `index` and `agentId` are read from a page.
 *
 * Usage:
 *   node scripts/migrate-demo.js --slug <name> [--apply]
 *   node scripts/migrate-demo.js --all [--apply]     (every dir under output/ except test)
 * Default is a dry run. --apply saves demo.html.pre-migrate next to each page first
 * (it may contain live keys: it is gitignored, delete it once you are happy).
 */

const fs = require('fs');
const path = require('path');
const {
  ROOT, deriveNames, demoDir, demoConfigPath, readDemoConfig, writeDemoConfig, foreignSlugRefs,
} = require('./lib/config');

const log = (m) => console.log(m);

// Exact text of the new form in template/index.html.
const NEW_CONFIG_BLOCK = [
  '// ============================================================',
  '// ELASTICSEARCH CONFIG',
  '// Values come from config.js (generated by `pnpm run inject`).',
  '// Never put credentials in this file.',
  '// ============================================================',
  "const ES_CONFIG = window.ES_CONFIG || { url: '', apiKey: '', index: '', kibanaUrl: '', kibanaApiKey: '', agentId: '' };",
].join('\n');
const SCRIPT_TAG_BLOCK = [
  '<!-- config.js is generated by `pnpm run inject -- --slug <name>` (gitignored; holds credentials). Missing in mock-only mode. -->',
  '<script src="config.js"></script>',
].join('\n');
const MSG_KIBANA = 'Agent Builder not configured. Run pnpm run setup -- --slug <name>, then pnpm run inject -- --slug <name>.';
const MSG_AGENT = 'Agent not configured. Run pnpm run setup -- --slug <name>, then pnpm run inject -- --slug <name>.';

const ES_CONFIG_RE = /const ES_CONFIG = \{[\s\S]*?\n\};?/g;
// Optional old banner comment sitting directly above the literal.
const OLD_BANNER_RE = /\/\/ =+\n\/\/ ELASTICSEARCH CONFIG\n(?:\/\/[^\n]*\n)*?\/\/ =+\n$/;

function pick(src, field) {
  const m = src.match(new RegExp(`\\b${field}\\s*:\\s*(['"])(.*?)\\1`));
  return m ? m[2] : null;
}

// Returns { html } (rewritten page) or { error }.
function rewritePage(html) {
  const matches = [...html.matchAll(ES_CONFIG_RE)];
  if (matches.length !== 1) {
    return { error: matches.length ? 'more than one ES_CONFIG literal' : 'no ES_CONFIG literal found' };
  }
  const m = matches[0];
  let start = m.index;
  const before = html.slice(0, start);
  const banner = before.match(OLD_BANNER_RE);
  if (banner) start -= banner[0].length;
  let out = html.slice(0, start) + NEW_CONFIG_BLOCK + html.slice(m.index + m[0].length);

  // Insert the config.js script tag directly before the <script> that holds ES_CONFIG.
  const at = out.indexOf(NEW_CONFIG_BLOCK);
  const tagAt = out.lastIndexOf('<script>', at);
  if (tagAt === -1) return { error: 'no <script> tag found before ES_CONFIG' };
  out = out.slice(0, tagAt) + SCRIPT_TAG_BLOCK + '\n' + out.slice(tagAt);

  // CSP: allow any https origin; the page itself no longer names hosts.
  out = out.replace(/connect-src [^;"]*;/, 'connect-src https:;');

  // Old token-prefix guards -> emptiness checks and the new messages.
  out = out.replace(/!ES_CONFIG\.kibanaUrl \|\| ES_CONFIG\.kibanaUrl\.startsWith\('\{\{'\)/g, '!ES_CONFIG.kibanaUrl');
  out = out.replace(/!ES_CONFIG\.agentId \|\| ES_CONFIG\.agentId\.startsWith\('\{\{'\)/g, '!ES_CONFIG.agentId');
  out = out.replace(/(if \(!ES_CONFIG\.kibanaUrl\) \{\s*return \{ message: )'[^']*'/, `$1'${MSG_KIBANA}'`);
  out = out.replace(/(if \(!ES_CONFIG\.agentId\) \{\s*return \{ message: )'[^']*'/, `$1'${MSG_AGENT}'`);
  return { html: out };
}

function postCheck(html) {
  const problems = [];
  if (/\b(?:apiKey|kibanaApiKey)\s*:\s*(['"`])[^'"`]+\1/i.test(html)) problems.push('non-empty apiKey/kibanaApiKey literal remains');
  if ((html.match(/<script src="config\.js"><\/script>/g) || []).length !== 1) problems.push('config.js script tag count is not 1');
  if (/const ES_CONFIG = \{/.test(html)) problems.push('old ES_CONFIG literal remains');
  return problems;
}

function migrate(slug, apply) {
  const dir = demoDir(slug);
  const page = path.join(dir, 'demo.html');
  const backup = page + '.pre-migrate';
  const tag = `[${slug}]`;

  if (!fs.existsSync(page)) { log(`${tag} SKIP: ${page} not found`); return 'skipped'; }
  const html = fs.readFileSync(page, 'utf8');
  if (html.includes('<script src="config.js">')) { log(`${tag} already migrated, skipping`); return 'already'; }

  const lit = [...html.matchAll(ES_CONFIG_RE)];
  if (lit.length !== 1) {
    log(`${tag} SKIP: ${lit.length ? 'more than one ES_CONFIG literal' : 'no ES_CONFIG literal found'}; no change`);
    return 'skipped';
  }

  // Only index and agentId are read from the page.
  const derived = deriveNames(slug, 'demo-products');
  const names = {};
  for (const [field, key, dflt] of [['indexName', 'index', derived.indexName], ['agentId', 'agentId', derived.agentId]]) {
    const v = pick(lit[0][0], key);
    if (!v || v.includes('{{')) {
      names[field] = dflt;
      log(`${tag} ${key}: derived ${dflt}`);
    } else {
      names[field] = v;
      log(`${tag} ${key}: kept-from-page ${v}`);
      if (v !== dflt) log(`${tag} WARNING: ${key} differs from derived default ${dflt}`);
    }
  }

  const refs = foreignSlugRefs(slug, { ...derived, ...names });
  if (refs.length) {
    for (const r of refs) log(`${tag} SKIP: ${r.field} "${r.value}" references another demo (${r.otherSlug}); resolve manually`);
    return 'skipped';
  }

  const res = rewritePage(html);
  if (res.error) { log(`${tag} SKIP: ${res.error}; no change`); return 'skipped'; }
  const problems = postCheck(res.html);
  if (problems.length) {
    log(`${tag} SKIP: post-check would fail (${problems.join('; ')}); no change`);
    return 'failed';
  }

  const hadConfig = fs.existsSync(demoConfigPath(slug));
  if (!apply) {
    log(`${tag} DRY RUN would: back up demo.html -> demo.html.pre-migrate`);
    log(`${tag} DRY RUN would: ${hadConfig ? 'keep existing' : 'write'} demo.config.json`);
    log(`${tag} DRY RUN would: swap ES_CONFIG for config.js loader, add <script src="config.js">, set CSP connect-src https:, update agent guards`);
    return 'planned';
  }

  if (fs.existsSync(backup)) { log(`${tag} SKIP: ${backup} already exists; move it aside first`); return 'skipped'; }
  fs.copyFileSync(page, backup);
  log(`${tag} saved backup demo.html.pre-migrate`);

  if (hadConfig && readDemoConfig(slug)) {
    log(`${tag} kept existing demo.config.json`);
  } else {
    writeDemoConfig(slug, { slug, ...derived, ...names });
    log(`${tag} wrote demo.config.json`);
  }

  fs.writeFileSync(page, res.html);
  const after = postCheck(fs.readFileSync(page, 'utf8'));
  if (after.length) {
    fs.copyFileSync(backup, page);
    fs.unlinkSync(backup);
    if (!hadConfig) fs.unlinkSync(demoConfigPath(slug));
    log(`${tag} FAILED post-check (${after.join('; ')}); restored original page`);
    return 'failed';
  }
  log(`${tag} migrated: ES_CONFIG now loads from config.js, CSP connect-src https:, agent guards updated`);
  log(`${tag} next: run \`pnpm run inject -- --slug ${slug}\` after recreating .env`);
  return 'migrated';
}

function main() {
  const args = process.argv.slice(2);
  const apply = args.includes('--apply');
  const si = args.indexOf('--slug');
  let slugs;
  if (args.includes('--all')) {
    const out = path.join(ROOT, 'output');
    slugs = fs.existsSync(out)
      ? fs.readdirSync(out, { withFileTypes: true }).filter(e => e.isDirectory() && e.name !== 'test').map(e => e.name).sort()
      : [];
  } else if (si !== -1 && args[si + 1] && !args[si + 1].startsWith('--')) {
    slugs = [args[si + 1]];
  } else {
    console.error('Usage: node scripts/migrate-demo.js (--slug <name> | --all) [--apply]');
    process.exit(2);
  }

  log(apply ? 'APPLY mode' : 'DRY RUN (no files written; add --apply to migrate)');
  // One bad dir must not abort the rest; any error still exits nonzero.
  const results = slugs.map(s => {
    try {
      return migrate(s, apply);
    } catch (err) {
      log(`[${s}] ERROR: ${err.message}; remaining steps skipped for this demo`);
      return 'failed';
    }
  });
  if (results.includes('failed')) process.exit(1);
}

main();
